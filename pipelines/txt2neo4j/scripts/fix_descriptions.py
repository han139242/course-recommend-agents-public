def find_exact_matches(node_name, fixes_dict):
    """Find the fix key that matches the node name."""
    if node_name in fixes_dict:
        return node_name
    # Try normalized comparison (handles encoding variations)
    for key in fixes_dict:
        if key.strip() == node_name.strip():
            return key
    return None


def is_template_description(desc):
    """Check if a description is a template/generic one."""
    patterns = [
        r'^.*是在.*常用的方法[。]?$',
        r'^围绕.*展开.*主题[。]?$',
        r'^围绕.*延展.*主题[。]?$',
        r'^.*是在.*常用的[。]?$',
        r'\?{4,}',  # garbled content
    ]
    for pat in patterns:
        if re.search(pat, desc):
            return True
    return False


def main():
    fixed_count = 0
    files_modified = 0

    for fname in sorted(os.listdir(COURSE_DIR)):
        if not fname.endswith('.json'):
            continue
        fpath = os.path.join(COURSE_DIR, fname)
        with open(fpath, 'r', encoding='utf-8') as f:
            data = json.load(f)

        modified = False
        for node in data.get('nodes', []):
            name = node.get('canonical_name', '')
            desc = node.get('description', '')

            # Fix by exact name match
            match_key = find_exact_matches(name, FIXES)
            if match_key:
                new_desc = FIXES[match_key]
                if node['description'] != new_desc:
                    print(f'  [NAME] ({data.get("course_title","?")}) {name}')
                    node['description'] = new_desc
                    modified = True
                    fixed_count += 1
            # Fix by pattern (template description)
            elif is_template_description(desc):
                # Generate a proper description from the name
                etype = node.get('entity_type', 'concept')
                generated = generate_description(name, etype)
                if generated and generated != desc:
                    print(f'  [PATTERN] ({data.get("course_title","?")}) {name}')
                    node['description'] = generated
                    modified = True
                    fixed_count += 1

        if modified:
            files_modified += 1
            with open(fpath, 'w', encoding='utf-8') as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
                f.write('\n')

    print(f'\nFixed {fixed_count} descriptions in {files_modified} files.')


