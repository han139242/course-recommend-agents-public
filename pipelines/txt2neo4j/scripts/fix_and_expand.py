def main():
    args = sys.argv[1:]
    dry_run = '--dry-run' in args

    # 1. Fix template descriptions in all existing files
    fixed_count = 0
    for fname in sorted(os.listdir(COURSE_DIR)):
        if not fname.endswith('.json'):
            continue
        fpath = os.path.join(COURSE_DIR, fname)
        with open(fpath, 'r', encoding='utf-8') as f:
            data = json.load(f)

        modified = False
        for node in data.get('nodes', []):
            name = node.get('canonical_name', '')
            if name in DESCRIPTION_FIXES:
                old = node['description']
                node['description'] = DESCRIPTION_FIXES[name]
                if old != node['description']:
                    modified = True
                    fixed_count += 1
                    print(f'  FIXED [{data.get("course_title","?")}] {name}')

        if modified and not dry_run:
            with open(fpath, 'w', encoding='utf-8') as f:
                json.dump(data, f, ensure_ascii=False, indent=2)
                f.write('\n')

    print(f'\nFixed {fixed_count} descriptions in existing files.')

    # 2. Create expansion files for weak courses
    for course_title, nodes in EXPANSION_NODES.items():
        safe_name = course_title.replace(' ', '_').replace('与', '_')
        fname = f'expansion_{safe_name}.json'
        fpath = os.path.join(COURSE_DIR, fname)

        batch = {
            'source': f'expansion_{safe_name}',
            'course_title': course_title,
            'nodes': [
                {
                    'canonical_name': name,
                    'entity_type': etype,
                    'description': desc,
                }
                for name, etype, desc in nodes
            ],
            'relations': [],
        }

        if not dry_run:
            with open(fpath, 'w', encoding='utf-8') as f:
                json.dump(batch, f, ensure_ascii=False, indent=2)
                f.write('\n')
            print(f'Created {fname} with {len(nodes)} nodes')
        else:
            print(f'[DRY RUN] Would create {fname} with {len(nodes)} nodes')

    print('\nDone.')


if __name__ == '__main__':
    main()
